(function () {
  const G = [
    // [ชื่อกลุ่ม, ระดับ(1-3), สมาชิกในกลุ่ม]
    ['อา', 1, 'กา ตา ปลา หมา ฟ้า ท่า นา ยา ขา ลา ว่า หา'],
    ['อี', 1, 'ดี ปี มี ที่ สี ผี หนี ขี่ ตี พี่ นี่ ชี กี่'],
    ['อู', 1, 'ปู หู ครู ดู รู งู หมู ตู้ ชู'],
    ['ไอ', 1, 'ไป ไม่ ไว ใจ ไร ไก่ ไข่ ไฟ ใหญ่ ให้ ใส ไทย ไหม ใบ'],
    ['โอ', 2, 'โต โล โม โซ โก โบ โจ โท'],
    ['อัน', 2, 'ฟัน วัน ขัน พัน กัน หัน ฉัน ปั้น มัน'],
    ['อม', 2, 'ลม ผม ขม ชม ส้ม นม ดม จม ก้ม ปม'],
    ['อง', 2, 'ลอง ของ ทอง น้อง ห้อง มอง กอง ร้อง ต้อง ฟอง สอง'],
    ['าง', 2, 'ช้าง ข้าง ทาง ล่าง บาง วาง ร้าง อ้าง นาง ยาง กลาง จาง ต่าง'],
    ['าน', 2, 'จาน งาน บาน ผ่าน ลาน นาน สาน ทาน ขาน ก้าน'],
    ['าว', 2, 'ข้าว ดาว ยาว สาว ราว ก้าว ลาว หาว'],
    ['เอือ', 3, 'เสือ เรือ เหนือ เมื่อ เนื้อ เบื่อ เหลือ เกลือ เพื่อ เชื่อ เจือ'],
    ['ัก', 3, 'รัก ปัก ชัก หัก พัก นัก ทัก หนัก จัก'],
    ['วน', 3, 'ป่วน ส่วน ล้วน หวน อ้วน กวน ชวน ด่วน'],
    ['ิว', 3, 'ผิว ริ้ว หิว']
  ].map(g => ({ name: g[0], level: g[1], words: g[2].split(' ') }));

  let seed = 20261025;
  const rnd = () => (seed = (seed * 1664525 + 1013904223) % 4294967296) / 4294967296;
  const shuffle = a => { a = a.slice(); for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(rnd() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; } return a; };

  const rows = []; let id = 1;
  G.forEach((g, gi) => {
    const others = shuffle(G.filter((_, i) => i !== gi)).slice(0, 3).flatMap(o => shuffle(o.words).slice(0, 3));
    g.words.slice(0, 5).forEach(w => {
      rows.push({
        id: id++, prompt: w,
        correct: g.words.filter(x => x !== w),
        distractors: shuffle(others).slice(0, 6),
        level: g.level, tag: 'สัมผัสสระ -' + g.name
      });
    });
  });
  window.TBK_SAMPLE_WORDS = rows;
})();
